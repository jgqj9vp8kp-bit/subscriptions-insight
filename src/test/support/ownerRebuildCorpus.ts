// Owner snapshot-rebuild golden corpus (access Phase 2; owner-regression review:
// "golden corpus blind spots — the rebuild is not covered").
//
// ownerSqlCorpus.ts proves the owner's READ SQL is byte-identical. The rebuild
// (rebuildCohortMembership, the owner's Rebuild and the post-sync auto-rebuild)
// is not a read runner, and Phase 2 adds work to it on purpose: the campaign
// scope (fact_campaign_scope) after activation and the retention ALTERs. This
// harness drives a rebuild with createRecordingClickHouse and a fake
// service-role Supabase and records, IN ORDER (the rebuild is sequential):
//   * every ClickHouse statement { kind, query, query_params, format, table, values };
//   * the Supabase RPC names.
// ownerRebuildGolden.test.ts removes the Phase-2 additions
// (isPhase2RebuildAddition / PHASE2_REBUILD_RPCS) from a recording of the
// current code and compares the rest byte for byte with
// src/test/fixtures/owner-rebuild-golden.json, recorded from the UNMODIFIED
// base code (4b4057e). So the owner's classifier INSERT, counts, version diff,
// validation and the claim / complete / fail sequence cannot drift unnoticed.
//
// Vitest-free on purpose (the base fixture is generated by bundling this file
// with the base tree's rebuild): the caller pins the clock.

