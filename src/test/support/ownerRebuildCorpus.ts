/** Fake warehouse answers, from the statement text alone. */
function respond(scenario: OwnerRebuildScenario) {
  return (statement: RecordedStatement): unknown[] => {
    const query = statement.query;
    if (query.includes("warehouse_hash")) {
      return [{ transaction_count: 500, unique_users: 120, max_row_version: "99", max_source_updated_at: "2026-10-05 23:00:00", warehouse_hash: "golden" }];
    }
    if (query.includes("(SELECT count() FROM dynamic) dynamic_users")) {
      return [{
        dynamic_users: 100,
        materialized_users: scenario.validation === "PASS" ? 100 : 99,
        duplicate_users: 0,
        missing_users: scenario.validation === "PASS" ? 0 : 1,
        extra_users: 0,
      }];
    }
    // fact_campaign_scope (current code only): evidence, then a matching read-back.
    if (query.includes("AS cid")) return [{ cid: "120210000000001", campaign_path: "soulmate-sketch", users: 5 }];
    if (query.includes("AS scope_rows")) return [{ scope_rows: 1, campaign_ids: 1, bad_resolved: 0, bad_mixed: 0, anchor_total: 5 }];
    if (query.includes("count() - uniqExact(canonical_user_id)")) return [{ c: 0 }];
    if (query.includes("common_users")) return [{ common_users: 90, unchanged_users: 80 }];
    if (query.includes("count() AS c")) return [{ c: 100 }];
    return [];
  };
}

/** Service-role Supabase: the snapshot state row for every read of it, empty
 * results elsewhere (the campaign alias map), `true` for every RPC. */
function fakeSupabase(previous: Readonly<Record<string, unknown>> | null, rpc: string[]): SupabaseLikeClient {
  return {
    from(table: string) {
      const rows = () => (table === "clickhouse_cohort_snapshot_state" && previous ? [JSON.parse(JSON.stringify(previous)) as Record<string, unknown>] : []);
      const builder = {
        select: () => builder,
        eq: () => builder,
        is: () => builder,
        order: () => builder,
        limit: () => builder,
        in: () => builder,
        maybeSingle: async (): Promise<SupabaseQueryResult> => ({ data: rows()[0] ?? null, error: null }),
        single: async (): Promise<SupabaseQueryResult> => ({ data: rows()[0] ?? null, error: null }),
        then: (resolve: (value: SupabaseQueryResult) => unknown, reject?: (reason: unknown) => unknown) =>
          Promise.resolve({ data: rows(), error: null }).then(resolve, reject),
      } as unknown as SupabaseQueryBuilder;
      return builder;
    },
    async rpc(functionName: string): Promise<SupabaseQueryResult> {
      rpc.push(functionName);
      return { data: true, error: null };
    },
  };
}

export interface OwnerRebuildStatement {
  kind: RecordedStatement["kind"];
  /** Key into OwnerRebuildCorpus.sql. */
  query: string;
  query_params: Record<string, unknown>;
  format?: string;
  table?: string;
  values?: unknown;
}

export interface OwnerRebuildRecord {
  /** "resolved" | "rejected:<ErrorName>". */
  outcome: string;
  rpc: string[];
  statements: OwnerRebuildStatement[];
}

export interface OwnerRebuildCorpus {
  format: string;
  base_commit: string;
  now: string;
  tenant: string;
  scenarios: Record<string, OwnerRebuildRecord>;
  sql: Record<string, string>;
}

export function ownerRebuildTextKey(text: string): string {
  return `q_${createHash("sha256").update(text, "utf8").digest("hex").slice(0, 16)}`;
}

/** Objects with sorted keys (recursively); arrays keep their order. */
function canonical(value: unknown): unknown {
  if (Array.isArray(value)) return value.map(canonical);
  if (value && typeof value === "object") {
    const out: Record<string, unknown> = {};
    for (const key of Object.keys(value as Record<string, unknown>).sort()) {
      const item = (value as Record<string, unknown>)[key];
      if (item !== undefined) out[key] = canonical(item);
    }
    return out;
  }
  return value;
}

function toStatement(statement: RecordedStatement, sql: Record<string, string>): OwnerRebuildStatement {
  const key = ownerRebuildTextKey(statement.query);
  if (sql[key] !== undefined && sql[key] !== statement.query) throw new Error(`owner rebuild corpus: content key collision on ${key}`);
  sql[key] = statement.query;
  const out: OwnerRebuildStatement = { kind: statement.kind, query: key, query_params: canonical(statement.params ?? {}) as Record<string, unknown> };
  if (statement.format !== undefined) out.format = statement.format;
  if (statement.table !== undefined) out.table = statement.table;
  if (statement.values !== undefined) out.values = canonical(statement.values);
  return out;
}

/** Runs every scenario with `rebuild`. The caller pins Date to OWNER_REBUILD_NOW. */
export async function recordOwnerRebuildCorpus(rebuild: OwnerRebuildFn, scenarios: readonly OwnerRebuildScenario[] = OWNER_REBUILD_SCENARIOS): Promise<OwnerRebuildCorpus> {
  if (new Date().toISOString() !== OWNER_REBUILD_NOW) throw new Error(`owner rebuild corpus: pin the clock to ${OWNER_REBUILD_NOW} first`);
  const sql: Record<string, string> = {};
  const records: Record<string, OwnerRebuildRecord> = {};
  for (const scenario of scenarios) {
    const clickhouse = createRecordingClickHouse(respond(scenario));
    const rpc: string[] = [];
    let outcome = "resolved";
    try {
      await rebuild({ authUserId: OWNER_REBUILD_TENANT, supabase: fakeSupabase(scenario.previous, rpc), clickhouse, force: scenario.force });
    } catch (error) {
      outcome = `rejected:${error instanceof Error ? error.name : typeof error}`;
    }
    records[scenario.id] = { outcome, rpc, statements: clickhouse.statements.map((statement) => toStatement(statement, sql)) };
  }
  const sortedSql: Record<string, string> = {};
  for (const key of Object.keys(sql).sort()) sortedSql[key] = sql[key];
  return {
    format: OWNER_REBUILD_CORPUS_FORMAT,
    base_commit: OWNER_REBUILD_BASE_COMMIT,
    now: OWNER_REBUILD_NOW,
    tenant: OWNER_REBUILD_TENANT,
    scenarios: records,
    sql: sortedSql,
  };
}

export function serializeOwnerRebuildCorpus(corpus: OwnerRebuildCorpus): string {
  return `${JSON.stringify(corpus, null, 2)}\n`;
}

