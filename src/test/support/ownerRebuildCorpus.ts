/** RPCs Phase 2 adds around the owner's claim / complete / fail sequence. */
export const PHASE2_REBUILD_RPCS: ReadonlySet<string> = new Set([
  "observe_clickhouse_cohort_snapshot_fingerprint",
  "set_clickhouse_campaign_scope_version",
]);

/** A statement Phase 2 adds to the rebuild: the fact_campaign_scope build
 * (ensure, evidence over fact_user_cohorts, existing ids, insert, read-back) or
 * the retention ALTER of either snapshot table. Everything else must be the
 * base statement, in order. */
export function isPhase2RebuildAddition(statement: OwnerRebuildStatement, sql: Record<string, string>): boolean {
  const text = sql[statement.query] ?? "";
  if (statement.kind === "insert") return statement.table === "fact_campaign_scope";
  if (/\bfact_campaign_scope\b/.test(text)) return true;
  // campaignScope.ts CAMPAIGN_SCOPE_EVIDENCE_SQL (reads the snapshot itself).
  if (text.includes(" AS cid,") && text.includes("GROUP BY cid, campaign_path")) return true;
  return /^ALTER TABLE (fact_user_cohorts|fact_campaign_scope) DELETE WHERE auth_user_id = \{auth_user_id:String\}\n  AND generated_at < /.test(text);
}

/** One scenario of `actual` with the Phase-2 additions removed (statement keys
 * re-pointed into `actual.sql`), for an ordered comparison with the base. */
export function withoutPhase2Additions(record: OwnerRebuildRecord, sql: Record<string, string>): OwnerRebuildRecord {
  return {
    outcome: record.outcome,
    rpc: record.rpc.filter((name) => !PHASE2_REBUILD_RPCS.has(name)),
    statements: record.statements.filter((statement) => !isPhase2RebuildAddition(statement, sql)),
  };
}
